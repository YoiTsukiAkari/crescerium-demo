/*:
 * @target MZ
 * @plugindesc スキルのメモ欄タグで、使用者(敵)が指定ステートを持っている間、
 * そのスキルを行動候補から除外します
 * @author DungeonEscape開発用
 *
 * @help DungeonEscape_ExcludeIfState.js
 *
 * ------------------------------------------------------------------
 * ◆概要
 * ------------------------------------------------------------------
 * RPGツクールMZの標準の行動パターン条件には「ステートを持っている」
 * 判定はありますが、「持っていない」判定は存在しません。
 * このプラグインは、その逆方向（既に持っているなら使わせない）を
 * 実現します。
 *
 * ------------------------------------------------------------------
 * ◆使い方
 * ------------------------------------------------------------------
 * スキルのメモ欄に以下のタグを記述してください。
 *
 * <excludeIfState:X>   使用者(敵)がステートID Xを持っている間、
 *                       このスキルは行動候補から除外される
 *
 * 例: ラーナの「粘毒の構え」に<excludeIfState:粘毒の構えステートID>と
 * 記述すれば、既に構え中の間は同じ技を選ばなくなり、他の行動
 * （通常攻撃など）が選ばれるようになります。
 *
 * ------------------------------------------------------------------
 * ◆注意点
 * ------------------------------------------------------------------
 * ・敵キャラ専用です（味方のスキル選択には影響しません）。
 * ・このタグにより除外された場合でも、他に候補が無ければ「何もしない」
 *   ことにはなりません。行動パターンには通常攻撃など、常に候補に
 *   残る行動を必ず1つ以上用意してください。
 */

/*:
 * @target MZ
 * @plugindesc スキルのメモ欄タグで、使用者(敵)が指定ステートを持っている間、
 * そのスキルを行動候補から除外します。同一ターン内での重複選出も防ぎます Ver2.0.0
 * @author DungeonEscape開発用
 *
 * @help DungeonEscape_ExcludeIfState.js
 *
 * ------------------------------------------------------------------
 * ◆概要
 * ------------------------------------------------------------------
 * RPGツクールMZの標準の行動パターン条件には「ステートを持っている」
 * 判定はありますが、「持っていない」判定は存在しません。
 * このプラグインは、その逆方向（既に持っているなら使わせない）を
 * 実現します。
 *
 * ------------------------------------------------------------------
 * ◆使い方
 * ------------------------------------------------------------------
 * スキルのメモ欄に以下のタグを記述してください。
 *
 * <excludeIfState:X>   使用者(敵)がステートID Xを持っている間、
 *                       このスキルは行動候補から除外される
 *
 * 例: ラーナの「粘毒の構え」に<excludeIfState:粘毒の構えステートID>と
 * 記述すれば、既に構え中の間は同じ技を選ばなくなり、他の行動
 * （通常攻撃など）が選ばれるようになります。
 *
 * ------------------------------------------------------------------
 * ◆Ver2.0.0の変更点（同一ターン内の重複選出を防止）
 * ------------------------------------------------------------------
 * RPGツクールMZの標準仕様では、1ターンに複数回行動する敵の場合、
 * その敵の行動候補リストは（ステートがまだ実際には付与されていない）
 * ターン開始時点で1回だけ作られ、その同じリストから複数回ぶんを
 * まとめて抽選する。そのため、1回目の行動でこのステートが新たに
 * 付与される技であっても、2回目以降の行動枠の抽選時点ではまだ
 * ステートが反映されておらず、同じ技が同一ターン内に重複して
 * 選ばれてしまうことがあった（<actionCountVariable>等で1ターンに
 * 複数回行動できる敵で特に起きやすい）。
 *
 * Ver2.0.0では、Game_Enemy.prototype.selectAllActionsを拡張し、
 * <excludeIfState>タグ付きの技が一度その ターンの行動枠に選ばれたら、
 * 同じターンの残りの行動枠の抽選対象からも除外するようにした。
 *
 * ------------------------------------------------------------------
 * ◆注意点
 * ------------------------------------------------------------------
 * ・敵キャラ専用です（味方のスキル選択には影響しません）。
 * ・このタグにより除外された場合でも、他に候補が無ければ「何もしない」
 *   ことにはなりません。行動パターンには通常攻撃など、常に候補に
 *   残る行動を必ず1つ以上用意してください。
 */

(() => {
  "use strict";

  const _Game_Enemy_isActionValid = Game_Enemy.prototype.isActionValid;
  Game_Enemy.prototype.isActionValid = function(action) {
    if (!_Game_Enemy_isActionValid.call(this, action)) return false;

    const skill = $dataSkills[action.skillId];
    const tag = skill ? skill.meta.excludeIfState : null;
    if (tag && this.isStateAffected(Number(tag))) {
      return false;
    }
    return true;
  };

  const _Game_Enemy_selectAllActions = Game_Enemy.prototype.selectAllActions;
  Game_Enemy.prototype.selectAllActions = function(actionList) {
    const ratingMax = Math.max(...actionList.map(a => a.rating));
    const ratingZero = ratingMax - 3;
    let list = actionList.filter(a => a.rating > ratingZero);

    for (let i = 0; i < this.numActions(); i++) {
      const chosen = this.selectAction(list, ratingZero);
      this.action(i).setEnemyAction(chosen);

      if (chosen) {
        const skill = $dataSkills[chosen.skillId];
        if (skill && skill.meta.excludeIfState) {
          // 同じターンの残り行動枠からは、この技を候補から外す
          list = list.filter(a => a.skillId !== chosen.skillId);
        }
      }
    }
  };
})();
