/*:
 * @target MZ
 * @plugindesc ステートのメモ欄タグで、素早さ(AGI)を割合ではなく
 * 絶対値で上書きするプラグイン Ver1.1.0
 * @author DungeonEscape開発用
 *
 * @help DungeonEscape_AgiOverride.js
 *
 * ------------------------------------------------------------------
 * ◆背景
 * ------------------------------------------------------------------
 * 標準の「特徴：通常能力値」は割合(%)でしか調整できないため、
 * 元の素早さが0の敵には、何%を掛けても0のままで効果が出ない。
 * また、割合を極端に大きくしたい場合、データベースのGUI上は
 * 1000%が上限になっている。
 *
 * このプラグインは、ステートのメモ欄で「この状態の間、素早さを
 * この絶対値にする」という指定ができるようにする。
 *
 * ------------------------------------------------------------------
 * ◆使い方
 * ------------------------------------------------------------------
 * 対象のステートのメモ欄に、以下のタグを記述してください。
 *
 *   <agiOverride:100>
 *
 * このステートを持っている間、素早さが(通常の計算式を無視して)
 * 指定した数値そのものになります。
 *
 * 例（今回のボス）:
 *   「俊敏化1」ステートに <agiOverride:100>
 *   「俊敏化2」ステートに <agiOverride:200>
 *   → バトルイベントで、HP60%以下になったら「俊敏化1」を付加、
 *     HP30%以下になったら「俊敏化1」を解除して「俊敏化2」を付加、
 *     とすればよい
 *
 * ------------------------------------------------------------------
 * ◆注意点
 * ------------------------------------------------------------------
 * ・このタグを持つステートを複数同時に持っている場合、その中で
 *   一番大きい数値が採用されます(数値が足し算・掛け算されることは
 *   ありません)。
 * ・このステートを解除すると、素早さは通常の計算(データベースの
 *   素早さ×特徴の割合など)に自動的に戻ります。
 *
 * ------------------------------------------------------------------
 * ◆Ver1.1.0の変更点
 * ------------------------------------------------------------------
 * 以前は計算式を丸ごと上書きしていたため、素早さデバフ(％低下や
 * 弱体化スタック)を後からかけても無視されてしまう不具合を修正。
 * 絶対値は「基準値」としてのみ使い、通常の割合特徴・バフ/デバフの
 * 倍率はその後も正しく乗算されるようにした。
 */

(() => {
  "use strict";

  const AGI_PARAM_ID = 6;

  const _Game_BattlerBase_param = Game_BattlerBase.prototype.param;
  Game_BattlerBase.prototype.param = function(paramId) {
    if (paramId === AGI_PARAM_ID) {
      const overrideStates = this.states().filter(s => s.meta.agiOverride);
      if (overrideStates.length > 0) {
        const baseOverride = Math.max(
          ...overrideStates.map(s => Number(s.meta.agiOverride))
        );
        // 絶対値を「基準値」として使い、そこに通常の割合特徴・
        // バフ/デバフの倍率をそのまま乗算する(丸ごと上書きはしない)
        const value =
          baseOverride * this.paramRate(paramId) * this.paramBuffRate(paramId);
        const maxValue = this.paramMax(paramId);
        const minValue = this.paramMin(paramId);
        return Math.round(value.clamp(minValue, maxValue));
      }
    }
    return _Game_BattlerBase_param.call(this, paramId);
  };
})();
