/*:
 * @target MZ
 * @plugindesc スキル・アイテムのメモ欄タグで、そのスキル/アイテム個別に
 * 会心率を加算できるようにするプラグイン
 * @author DungeonEscape開発用
 *
 * @help DungeonEscape_SkillCriticalBonus.js
 *
 * ------------------------------------------------------------------
 * ◆概要
 * ------------------------------------------------------------------
 * RPGツクールMZの標準仕様では、会心率(cri)は使用者側のパラメータで
 * 決まり、スキル側で個別に持てるのは「会心あり/なし」のON/OFFだけです。
 * このプラグインを使うと、そこに「このスキルだけ+X%」という上乗せを
 * 追加できます。
 *
 * ------------------------------------------------------------------
 * ◆使い方
 * ------------------------------------------------------------------
 * スキル・アイテムのメモ欄に以下のタグを記述してください。
 *
 * <criticalRateBonus:X>   会心率にX%を上乗せする
 *
 * 例: <criticalRateBonus:5>
 *   → 使用者本来の会心率(例:5%)に+5%して、このスキルだけ10%になる
 *
 * ------------------------------------------------------------------
 * ◆注意点
 * ------------------------------------------------------------------
 * ・対象のスキル/アイテムは、データベース上で「会心」にチェックが
 *   入っている必要があります（チェックが無いと、そもそも会心自体が
 *   発生しないため、このタグを付けても効果はありません）。
 */

(() => {
  "use strict";

  const _Game_Action_itemCri = Game_Action.prototype.itemCri;
  Game_Action.prototype.itemCri = function(target) {
    let cri = _Game_Action_itemCri.call(this, target);

    const item = this.item();
    if (item && item.damage.critical && item.meta.criticalRateBonus) {
      cri += Number(item.meta.criticalRateBonus) / 100;
    }

    return cri;
  };
})();
