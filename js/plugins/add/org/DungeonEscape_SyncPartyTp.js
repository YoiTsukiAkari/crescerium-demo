/*:ja
 * @target MZ
 * @plugindesc スキルのメモ欄タグで、使用者以外の生存中の味方からも同じTPコストを消費させます (Ver1.0.0)
 * @author DungeonEscape開発用
 *
 * @help DungeonEscape_SyncPartyTp.js
 *
 * ------------------------------------------------------------------
 * ◆概要
 * ------------------------------------------------------------------
 * スキルのメモ欄に以下のタグを書くと、そのスキルを使った時、
 * 使用者以外の生存中の味方全員からも、同じ量のTPを消費します。
 *
 *   <syncPartyTp>
 *
 * 消費量は、そのスキル自体に設定されている[TPコスト]の値を
 * そのまま使います。数値をこのタグ側で個別に指定する必要は
 * ありません(スキル本体のTPコストと必ず一致するため、
 * 数値の二重管理・食い違いが起きません)。
 *
 * ------------------------------------------------------------------
 * ◆使い方
 * ------------------------------------------------------------------
 * 連携技(クレイが使うスキル)のメモ欄に <syncPartyTp> を追加する
 * だけで動作します。TPコストの数値自体は、今まで通りスキューの
 * [TPコスト]欄で設定・調整してください。
 *
 * ------------------------------------------------------------------
 * ◆注意点
 * ------------------------------------------------------------------
 * ・TPコストが0のスキルには何も起こりません。
 * ・味方のTPが0未満にはなりません(自動でクランプされます)。
 * ・このタグはアクター(味方)が使った場合のみ動作します。
 *
 * 利用規約:このプロジェクト専用プラグインです。
 */

(() => {
    "use strict";

    const _Game_Battler_useItem = Game_Battler.prototype.useItem;
    Game_Battler.prototype.useItem = function (item) {
        _Game_Battler_useItem.call(this, item);

        if (this.isActor() && item && item.meta && "syncPartyTp" in item.meta) {
            const tpCost = item.tpCost || 0;
            if (tpCost > 0) {
                const others = $gameParty.battleMembers().filter(
                    member => member !== this && member.isAlive()
                );
                for (const member of others) {
                    member.gainSilentTp(-tpCost);
                }
            }
        }
    };
})();
